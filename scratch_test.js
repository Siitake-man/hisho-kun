    function runAutoPilotCycle() {
      if (!autoPilotActive) return;
      const cycle = [
        { pose: 'front',   x: 190 },
        { pose: 'back',    x: 235 }, // 本棚の前へ歩いて後ろ姿！
        { pose: 'reading', x: 235 }, // 本を読む
        { pose: 'tea',     x: 160 }, // お茶を飲む
        { pose: 'lay',     x: 120 }  // 暖炉の横で寝転ぶ
      ];
      const r = cycle[Math.floor(Math.random() * cycle.length)];
      selectPose(r.pose);
      targetPetX = r.x;
    }

    function toggleAutoPilot() {
      autoPilotActive = !autoPilotActive;
      const pill = document.getElementById('autopilot-pill');
      if (autoPilotActive) {
        pill.innerText = 'ON';
        pill.style.background = 'var(--accent-green)';
        autoPilotTimer = setInterval(runAutoPilotCycle, 4500);
      } else {
        pill.innerText = 'OFF';
        pill.style.background = '#888';
        clearInterval(autoPilotTimer);
      }
    }

