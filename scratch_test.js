    // アンビエント光芒
    function drawAmbientLighting(c) {
      const w = 380, h = 350;
      const spot = c.createRadialGradient(w / 2, 40, 10, w / 2, 140, 240);
      spot.addColorStop(0, 'rgba(255, 215, 100, 0.2)');
      spot.addColorStop(0.6, 'rgba(255, 160, 50, 0.08)');
      spot.addColorStop(1, 'rgba(0, 0, 0, 0.45)');
      c.fillStyle = spot;
      c.fillRect(0, 0, w, h);

      ambientDust.forEach(p => {
        p.y += p.speedY;
        p.x += p.speedX;
        p.pulse += 0.04;
        if (p.y < 0) { p.y = h; p.x = Math.random() * w; }
        const a = p.alpha * (0.6 + 0.4 * Math.sin(p.pulse));
        c.fillStyle = `rgba(255, 210, 110, ${a})`;
        c.beginPath();
        c.arc(p.x, p.y, p.r, 0, Math.PI * 2);
        c.fill();
      });
    }

